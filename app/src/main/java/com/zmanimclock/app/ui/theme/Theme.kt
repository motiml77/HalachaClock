/** Extended (non-M3) roles — style 1D. See [ExtendedColors]. */
val LocalExtendedColors = staticCompositionLocalOf { ExtendedLight }

/** Convenience accessor: `Ext.colors.accentGold`. */
object Ext {
    val colors: ExtendedColors
        @Composable get() = LocalExtendedColors.current
}

/**
 * App theme — style 1D "קריאוּת מרבית" (Claude Design). Dynamic color is
 * intentionally disabled so the palette renders exactly as designed; the
 * [dynamicColor] parameter is kept for API stability. The entire app is
 * RTL (Hebrew-first), forced at the theme level.
 */
@Composable
fun ZmanimTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme
    val extended = if (darkTheme) ExtendedDark else ExtendedLight

    CompositionLocalProvider(
        LocalLayoutDirection provides LayoutDirection.Rtl,
        LocalExtendedColors provides extended,
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            content = content,
        )
    }
}
